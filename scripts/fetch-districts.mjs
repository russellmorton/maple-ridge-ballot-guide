// Downloads the official boundaries of the ridings in provincial/data.js from
// DataBC and writes:
//   lib/districts.js     detailed (5 m), for the address lookup
//   provincial/map.js    light (60 m), for the riding map on the page
// Coordinates stay in BC Albers (EPSG:3005, metres).
//
// Run: node scripts/fetch-districts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
import { DISTRICTS_WFS, DISTRICT_LAYER } from "../lib/riding-lookup.js";

const root = new URL("..", import.meta.url);
const sandbox = { window: {} };
vm.runInNewContext(readFileSync(new URL("provincial/data.js", root), "utf8"), sandbox);
const ridings = sandbox.window.GUIDE.ridings;

const u = new URL(DISTRICTS_WFS);
u.search = new URLSearchParams({
  service: "WFS",
  version: "2.0.0",
  request: "GetFeature",
  typeName: DISTRICT_LAYER,
  outputFormat: "application/json",
  srsName: "EPSG:3005",
  propertyName: "ED_NAME,SHAPE",
  CQL_FILTER: `ED_NAME IN (${ridings.map((r) => `'${r.name.replace(/'/g, "''")}'`).join(",")})`,
});
const r = await fetch(u);
if (!r.ok) throw new Error(`DataBC returned ${r.status}`);
const fc = await r.json();

// Douglas–Peucker on one ring, keeping it closed.
function simplify(ring, tol) {
  if (ring.length < 5) return ring;
  const keep = new Uint8Array(ring.length);
  keep[0] = keep[ring.length - 1] = 1;
  const stack = [[0, ring.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = ring[a];
    const [bx, by] = ring[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy);
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = ring[i];
      const d = len ? Math.abs(dy * px - dx * py + bx * ay - by * ax) / len : Math.hypot(px - ax, py - ay);
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  const out = ring.filter((_, i) => keep[i]);
  return out.length >= 4 ? out : ring;
}

const round = (ring) => ring.map(([x, y]) => [Math.round(x), Math.round(y)]);
const asMulti = (g) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates);
const build = (tol) =>
  ridings.map((riding) => {
    const f = fc.features.find((x) => x.properties.ED_NAME === riding.name);
    if (!f) throw new Error(`No boundary found for "${riding.name}". Check the name against DataBC's ED_NAME.`);
    return { id: riding.id, name: riding.name, polygons: asMulti(f.geometry).map((poly) => poly.map((ring) => round(simplify(ring, tol)))) };
  });

const fetched = new Date().toISOString().slice(0, 10);
const source = "DataBC, Current Provincial Electoral Districts of British Columbia (WHSE_ADMIN_BOUNDARIES.EBC_PROV_ELECTORAL_DIST_SVW)";
const detailed = build(5);
const light = build(60);

writeFileSync(new URL("lib/districts.js", root), `// Official boundaries of the ridings the provincial guide covers, in BC Albers
// (EPSG:3005, metres), simplified to 5 m. Generated by scripts/fetch-districts.mjs
// from DataBC; don't edit by hand.
export default ${JSON.stringify({ source, fetched, districts: detailed.map(({ name, polygons }) => ({ name, polygons })) })};
`);
writeFileSync(new URL("provincial/map.js", root), `// Riding outlines for the map on the provincial guide, in BC Albers (EPSG:3005,
// metres), simplified to 60 m. Generated by scripts/fetch-districts.mjs; don't edit by hand.
window.RIDING_MAP = ${JSON.stringify({ source, fetched, districts: light })};
`);
const pts = (list) => list.reduce((n, d) => n + d.polygons.flat().reduce((m, ring) => m + ring.length, 0), 0);
console.log(`Wrote ${detailed.length} ridings: ${pts(detailed)} points (lookup), ${pts(light)} points (map).`);
